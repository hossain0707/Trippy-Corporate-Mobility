export const language = localStorage.getItem('trippy-language') === 'bn' ? 'bn' : 'en';
export const locale = language === 'bn' ? 'bn-BD' : 'en-BD';
export const localText = (english, bangla) => language === 'bn' ? bangla : english;
export const t = text => language === 'bn' && Object.hasOwn(messages, text) ? messages[text] : text;

export function initializeLanguage() {
  document.documentElement.lang = language;
  const textNodes = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (textNodes.nextNode()) {
    const item = textNodes.currentNode;
    const content = item.nodeValue.trim();
    if (content && t(content) !== content) item.nodeValue = item.nodeValue.replace(content, t(content));
  }
  document.querySelectorAll('[aria-label], [placeholder]').forEach(element => {
    for (const name of ['aria-label', 'placeholder']) {
      if (element.hasAttribute(name)) element.setAttribute(name, t(element.getAttribute(name)));
    }
  });
  const toggle = document.getElementById('languageBtn');
  toggle.textContent = language === 'bn' ? 'English' : 'বাংলা';
  toggle.lang = language === 'bn' ? 'en' : 'bn';
  toggle.onclick = () => {
    localStorage.setItem('trippy-language', language === 'bn' ? 'en' : 'bn');
    location.reload();
  };
}
